"""Build the single-file aarch64 ``lwd_source_poc`` launcher.

The launcher embeds three things:

* one self-contained Python bundle: ``lwd_poc.py`` with ``lwd_source_runtime.py``
  and ``discover_lwd_sources.py`` installed as in-memory pseudo-modules;
* the manifest and declarative scope, both also available to the bundled tool;
* the raw 32 key bytes, kept out of the Python bundle entirely.

The key is decoded from the baseline ``runtime_key.b64`` and validated here.
Its base64 text is never written into the generated C file, the bundle, the
build log or the worktree.  At run time the launcher writes the bundle into an
anonymous ``memfd``, exports the base64 key through ``LWD_SOURCE_KEY_B64`` and
execs Python on ``/proc/self/fd/<N>``; nothing is written to disk.

All generated sources live in a private ``TemporaryDirectory`` and disappear
once compilation finishes.

Example (inside WSL/Linux, where the cross compiler is installed)::

    python3 tools/lwd_source_encryption/build_lwd_source_poc.py \\
        --source-dir /path/to/baseline/tools/lwd_source_encryption \\
        --output tools/lwd_source_encryption/lwd_source_poc
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

import pybase64 as base64

DEFAULT_CC = "aarch64-linux-gnu-gcc"
EXPECTED_KEY_BYTES = 32
# Source from the bundle; manifest.json is both inlined in the bundle and
# embedded separately for --lwd-extract-to.
TOOL_SOURCE = "lwd_poc.py"
RUNTIME_SOURCE = "lwd_source_runtime.py"
DISCOVERY_SOURCE = "discover_lwd_sources.py"
MANIFEST = "manifest.json"
SCOPE = "lwd_source_scope.json"
KEY_ASSET = "runtime_key.b64"


def _die(message: str) -> None:
    print(f"error: {message}", file=sys.stderr)
    raise SystemExit(1)


def _decode_runtime_key(name: str, text: bytes) -> bytes:
    try:
        key = base64.b64decode(text.strip(), validate=True)
    except Exception as exc:  # noqa: BLE001 - report any decoder failure
        _die(f"{name} is not valid base64: {exc}")
    if len(key) != EXPECTED_KEY_BYTES:
        _die(f"{name} decodes to {len(key)} bytes, expected {EXPECTED_KEY_BYTES}")
    # The launcher re-encodes the raw bytes; require the baseline text to be
    # the canonical encoding so the environment variable matches it exactly.
    if base64.b64encode(key) != text.strip():
        _die(
            f"{name} is not canonical standard base64; the launcher re-encodes "
            "the raw key bytes and must reproduce the same text"
        )
    return key


def _b64_literal(data: bytes, indent: str) -> str:
    encoded = base64.b64encode(data).decode("ascii")
    chunks = [
        encoded[offset : offset + 76] for offset in range(0, len(encoded), 76)
    ] or [""]
    lines = "\n".join(f'{indent}"{chunk}"' for chunk in chunks)
    close_indent = indent[:-4]
    return f"(\n{lines}\n{close_indent})"


def _bundle_source(
    tool_source: bytes,
    runtime_source: bytes,
    discovery_source: bytes,
    manifest: bytes,
    scope: bytes,
) -> bytes:
    """Return the single-file Python bundle compiled into the launcher."""
    scope_sha256 = hashlib.sha256(scope).hexdigest()
    preamble = f"""# Generated by build_lwd_source_poc.py; do not edit.
# Runtime and discovery are in-memory pseudo-modules; no source is written.
import pybase64 as _lwd_b64
import json as _lwd_json
import sys as _lwd_sys
import types as _lwd_types

_LWD_RUNTIME_SOURCE = _lwd_b64.b64decode(
    {_b64_literal(runtime_source, "        ")}
).decode("utf-8")
_lwd_runtime = _lwd_types.ModuleType("lwd_source_runtime")
_lwd_runtime.__file__ = "<lwd_source_runtime (bundled)>"
_lwd_runtime.__bundled_source__ = _LWD_RUNTIME_SOURCE
_lwd_sys.modules["lwd_source_runtime"] = _lwd_runtime
exec(compile(_LWD_RUNTIME_SOURCE, _lwd_runtime.__file__, "exec"),
     _lwd_runtime.__dict__)

_LWD_DISCOVERY_SOURCE = _lwd_b64.b64decode(
    {_b64_literal(discovery_source, "        ")}
).decode("utf-8")
_lwd_discovery = _lwd_types.ModuleType("discover_lwd_sources")
_lwd_discovery.__file__ = "<discover_lwd_sources (bundled)>"
_lwd_discovery.__bundled_scope__ = _lwd_json.loads(
    _lwd_b64.b64decode(
        {_b64_literal(scope, "            ")}
    ).decode("utf-8")
)
_lwd_discovery.__bundled_scope_sha256__ = {scope_sha256!r}
_lwd_sys.modules["discover_lwd_sources"] = _lwd_discovery
exec(compile(_LWD_DISCOVERY_SOURCE, _lwd_discovery.__file__, "exec"),
     _lwd_discovery.__dict__)

MANIFEST_JSON = _lwd_json.loads(
    _lwd_b64.b64decode(
        {_b64_literal(manifest, "            ")}
    ).decode("utf-8")
)
_lwd_tool_source = _lwd_b64.b64decode(
    {_b64_literal(tool_source, "        ")}
).decode("utf-8")
del _LWD_RUNTIME_SOURCE, _LWD_DISCOVERY_SOURCE
del _lwd_runtime, _lwd_discovery, _lwd_sys, _lwd_types, _lwd_b64, _lwd_json

exec(compile(_lwd_tool_source, __file__, "exec"), globals())
"""
    return preamble.encode("utf-8")


def _read_assets(
    source_dir: Path,
) -> tuple[bytes, bytes, bytes, bytes, bytes, bytes]:
    names = (
        TOOL_SOURCE,
        RUNTIME_SOURCE,
        DISCOVERY_SOURCE,
        MANIFEST,
        SCOPE,
        KEY_ASSET,
    )
    for name in names:
        if not (source_dir / name).is_file():
            _die(f"missing asset: {source_dir / name}")
    assets = {name: (source_dir / name).read_bytes() for name in names}
    try:
        manifest_data = json.loads(assets[MANIFEST])
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        _die(f"manifest is not valid JSON: {exc}")
    if manifest_data.get("expected_total") != len(manifest_data.get("modules", [])):
        _die("manifest expected_total does not match its module count")
    key = _decode_runtime_key(KEY_ASSET, assets[KEY_ASSET])
    return (
        assets[TOOL_SOURCE],
        assets[RUNTIME_SOURCE],
        assets[DISCOVERY_SOURCE],
        assets[MANIFEST],
        assets[SCOPE],
        key,
    )


def _sha256(data: bytes) -> bytes:
    return hashlib.sha256(data).digest()


def _c_bytes(data: bytes, indent: str = "    ") -> str:
    chunks = []
    for offset in range(0, len(data), 12):
        block = data[offset : offset + 12]
        chunks.append(indent + ", ".join(f"0x{byte:02x}" for byte in block))
    return ",\n".join(chunks)


def _c_array(declaration: str, data: bytes) -> str:
    return f"{declaration} = {{\n{_c_bytes(data)}\n}};"


def _c_digest(name: str, digest: bytes) -> str:
    body = ", ".join(f"0x{byte:02x}" for byte in digest)
    return f"const unsigned char {name}[32] = {{{body}}};"


def _write_generated_assets(
    directory: Path,
    tool_source: bytes,
    runtime_source: bytes,
    discovery_source: bytes,
    manifest: bytes,
    scope: bytes,
    key: bytes,
) -> tuple[Path, bytes]:
    bundle = _bundle_source(
        tool_source, runtime_source, discovery_source, manifest, scope
    )
    header = directory / "lwd_source_poc_assets.h"
    header.write_text(
        """/* Generated by build_lwd_source_poc.py; do not edit. */
#ifndef LWD_SOURCE_POC_ASSETS_H
#define LWD_SOURCE_POC_ASSETS_H

#include <stddef.h>

/* The Python bundle executed from an anonymous memfd. */
extern const unsigned char lwd_bundle_data[];
extern const size_t lwd_bundle_size;
/* Manifest bytes, inlined in the bundle and exposed for the debug extractor. */
extern const unsigned char lwd_manifest_data[];
extern const size_t lwd_manifest_size;
/* Raw AES-256 key bytes; base64-encoded into the environment before exec. */
extern const unsigned char lwd_source_key[32];

/* Non-secret metadata reported by --lwd-print-meta. */
extern const unsigned char lwd_bundle_sha256[32];
extern const unsigned char lwd_manifest_sha256[32];
extern const unsigned char lwd_tool_source_sha256[32];
extern const unsigned char lwd_runtime_source_sha256[32];
extern const unsigned char lwd_discovery_source_sha256[32];
extern const unsigned char lwd_scope_sha256[32];
extern const size_t lwd_tool_source_size;
extern const size_t lwd_runtime_source_size;
extern const size_t lwd_discovery_source_size;
extern const size_t lwd_scope_size;

#endif
""",
        encoding="utf-8",
        newline="\n",
    )

    lines = [
        "/* Generated by build_lwd_source_poc.py; do not edit. */",
        '#include "lwd_source_poc_assets.h"',
        "",
        _c_array("const unsigned char lwd_bundle_data[]", bundle),
        "const size_t lwd_bundle_size = sizeof(lwd_bundle_data);",
        "",
        _c_array("const unsigned char lwd_manifest_data[]", manifest),
        "const size_t lwd_manifest_size = sizeof(lwd_manifest_data);",
        "",
        _c_array("const unsigned char lwd_source_key[32]", key),
        "",
        _c_digest("lwd_bundle_sha256", _sha256(bundle)),
        _c_digest("lwd_manifest_sha256", _sha256(manifest)),
        _c_digest("lwd_tool_source_sha256", _sha256(tool_source)),
        _c_digest("lwd_runtime_source_sha256", _sha256(runtime_source)),
        _c_digest("lwd_discovery_source_sha256", _sha256(discovery_source)),
        _c_digest("lwd_scope_sha256", _sha256(scope)),
        f"const size_t lwd_tool_source_size = {len(tool_source)};",
        f"const size_t lwd_runtime_source_size = {len(runtime_source)};",
        f"const size_t lwd_discovery_source_size = {len(discovery_source)};",
        f"const size_t lwd_scope_size = {len(scope)};",
        "",
    ]
    source = directory / "lwd_source_poc_assets.c"
    source.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    return source, bundle


def _find_compiler(requested: str) -> str:
    resolved = shutil.which(requested)
    if resolved is None:
        _die(
            f"cross compiler {requested!r} not found; install "
            "gcc-aarch64-linux-gnu (e.g. inside WSL: apt-get install "
            "gcc-aarch64-linux-gnu) or pass --cc"
        )
    return resolved


def _compile(
    cc: str, launcher: Path, assets_source: Path, include_dir: Path, output: Path
) -> None:
    output.parent.mkdir(parents=True, exist_ok=True)
    command = [
        cc,
        "-static",
        "-O2",
        "-std=c11",
        "-Wall",
        "-Wextra",
        "-Wl,--build-id=none",
        f"-I{include_dir}",
        "-o",
        str(output),
        str(launcher),
        str(assets_source),
    ]
    print("compile:", " ".join(command), flush=True)
    subprocess.run(command, check=True)
    output.chmod(0o755)


def _qemu_checks(qemu: str, output: Path, workdir: Path) -> None:
    resolved = shutil.which(qemu)
    if resolved is None:
        _die(f"QEMU executable {qemu!r} not found; install qemu-user")

    def run(arguments: list[str]) -> subprocess.CompletedProcess[str]:
        completed = subprocess.run(
            [resolved, str(output), *arguments],
            capture_output=True,
            text=True,
            timeout=180,
        )
        if completed.returncode != 0:
            detail = (completed.stderr or completed.stdout).strip()[-2000:]
            _die(
                f"QEMU check {arguments!r} failed with exit "
                f"{completed.returncode}: {detail}"
            )
        return completed

    metadata = json.loads(run(["--lwd-print-meta"]).stdout)
    if metadata.get("transport") != "memfd":
        _die("QEMU metadata does not report memfd transport")
    run(["--lwd-help"])
    purelib = workdir / "qemu_purelib"
    run(["uninstall", "--purelib", str(purelib)])
    print("qemu: metadata/help/memfd Python bundle checks passed")


def build(
    source_dir: Path,
    output: Path,
    launcher: Path,
    cc_requested: str,
    fingerprint_only: bool,
    qemu_requested: str | None,
) -> int:
    (
        tool_source,
        runtime_source,
        discovery_source,
        manifest,
        scope,
        key,
    ) = _read_assets(source_dir)

    print(f"source-dir: {source_dir}")
    for name, data in (
        (TOOL_SOURCE, tool_source),
        (RUNTIME_SOURCE, runtime_source),
        (DISCOVERY_SOURCE, discovery_source),
        (MANIFEST, manifest),
        (SCOPE, scope),
    ):
        print(f"  {name}: {len(data)} bytes sha256={hashlib.sha256(data).hexdigest()}")
    print(
        f"  {KEY_ASSET}: embedded as {len(key)} raw bytes "
        "(base64 text not written anywhere)"
    )

    if fingerprint_only:
        return 0

    cc = _find_compiler(cc_requested)
    if not launcher.is_file():
        _die(f"launcher template not found: {launcher}")

    with tempfile.TemporaryDirectory(prefix="lwd_source_poc_build_") as tmp:
        tmp_dir = Path(tmp)
        assets_source, bundle = _write_generated_assets(
            tmp_dir,
            tool_source,
            runtime_source,
            discovery_source,
            manifest,
            scope,
            key,
        )
        print(
            f"  bundle: {len(bundle)} bytes sha256={hashlib.sha256(bundle).hexdigest()}"
        )
        _compile(cc, launcher, assets_source, tmp_dir, output)
        if qemu_requested is not None:
            _qemu_checks(qemu_requested, output, tmp_dir)

    output_bytes = output.read_bytes()
    if base64.b64encode(key) in output_bytes:
        _die("base64 key text unexpectedly occurs in the ELF")
    digest = hashlib.sha256(output_bytes).hexdigest()
    size = len(output_bytes)
    print(f"output: {output}")
    print(f"size: {size} bytes")
    print(f"sha256: {digest}")
    return 0


def main(argv: list[str] | None = None) -> int:
    script_dir = Path(__file__).resolve().parent
    parser = argparse.ArgumentParser(
        description="Build the single-file aarch64 lwd_source_poc launcher."
    )
    parser.add_argument(
        "--source-dir",
        type=Path,
        default=script_dir,
        help="asset directory (default: the build script's own directory)",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=script_dir / "lwd_source_poc",
        help="output ELF path (default: <script dir>/lwd_source_poc)",
    )
    parser.add_argument(
        "--launcher",
        type=Path,
        default=script_dir / "lwd_source_poc_launcher.c",
        help="C launcher template (default: <script dir>/lwd_source_poc_launcher.c)",
    )
    parser.add_argument(
        "--cc",
        default=os.environ.get("CROSS_CC", DEFAULT_CC),
        help=f"aarch64 Linux cross compiler (default: ${DEFAULT_CC})",
    )
    parser.add_argument(
        "--qemu",
        nargs="?",
        const="qemu-aarch64",
        default=None,
        help="run metadata/help/memfd bundle checks with qemu-aarch64",
    )
    parser.add_argument(
        "--fingerprint-only",
        action="store_true",
        help="print source hashes without compiling",
    )
    args = parser.parse_args(argv)

    source_dir = args.source_dir.resolve()
    if not source_dir.is_dir():
        _die(f"source-dir is not a directory: {source_dir}")
    return build(
        source_dir=source_dir,
        output=args.output.resolve(),
        launcher=args.launcher.resolve(),
        cc_requested=args.cc,
        fingerprint_only=args.fingerprint_only,
        qemu_requested=args.qemu,
    )


if __name__ == "__main__":
    sys.exit(main())
